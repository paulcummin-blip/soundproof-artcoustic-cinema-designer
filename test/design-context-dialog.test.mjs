import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {createRequire} from 'node:module';
import {pathToFileURL} from 'node:url';
import {transformSync} from 'esbuild';
import React from 'react';
import Renderer,{act} from 'react-test-renderer';
const require=createRequire(import.meta.url);
test('dialog edits remain visible through failed save, new and undone rows are editable, only persisted answers say Saved',async()=>{
let source=await fs.readFile('src/components/adi/designContext/DesignContextDialog.jsx','utf8');
source=source.replace("import React from 'react';","import React from "+JSON.stringify(pathToFileURL(require.resolve('react')).href)+";");
source=source.replace(/import \{[\s\S]*?\} from '@\/components\/ui\/dialog';/,"const Plain=({children})=>React.createElement('div',null,children); const Dialog=Plain,DialogContent=Plain,DialogHeader=Plain,DialogTitle=Plain,DialogDescription=Plain,DialogFooter=Plain;");
source=source.replace(/import \{[^}]*\} from 'lucide-react';/,"const HelpCircle=()=>null,Check=()=>null,MinusCircle=()=>null,Edit3=()=>null;");
source=source.replace(/import \{[\s\S]*?\} from '@\/components\/report\/typography\/reportTypography';/,"const FONT_HEADING='test',FONT_BODY='test';");
const compiled=transformSync(source,{loader:'jsx',format:'esm'}).code;
const {default:Dialog}=await import('data:text/javascript;base64,'+Buffer.from(compiled).toString('base64'));
const question={question_id:'seating',question:'Why?',area:'seating',decision_fingerprint:'fp'};
const props={open:true,questions:[question],savedItems:[],onProceed:rows=>submitted=rows};let submitted,view;
const button=name=>view.root.findAllByType('button').find(n=>n.children.join('')===name);
await act(async()=>{view=Renderer.create(React.createElement(Dialog,props));});
assert.equal(view.root.findAllByType('textarea').length,1,'new question editable');
await act(async()=>view.root.findByType('textarea').props.onChange({target:{value:'Reserve space for a bar.'}}));
assert.equal(view.root.findByType('textarea').props.value,'Reserve space for a bar.');
await act(async()=>view.update(React.createElement(Dialog,{...props,isSaving:true})));
assert.equal(view.root.findByType('fieldset').props.disabled,true);
await act(async()=>view.update(React.createElement(Dialog,{...props,error:'Save failed. Retry.'})));
assert.equal(view.root.findByType('textarea').props.value,'Reserve space for a bar.','failed save retains typed answer');
assert.ok(button('Retry Save'));assert.equal(view.root.findAll(n=>n.type==='div'&&n.children.includes('Saved')).length,0,'unsaved edit not labelled saved');
await act(async()=>button('Retry Save').props.onClick());assert.equal(submitted[0].answer,'Reserve space for a bar.');
const skip=view.root.findAllByType('button').find(n=>n.children.some(x=>typeof x==='string'&&x.includes('Skip for this generation')));
await act(async()=>skip.props.onClick());assert.equal(view.root.findAllByType('textarea').length,0);
await act(async()=>button('Undo').props.onClick());assert.equal(view.root.findAllByType('textarea').length,1,'undo restores editability');
await act(async()=>view.unmount());
});
