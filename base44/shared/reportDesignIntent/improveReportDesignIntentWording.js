/**
 * improveReportDesignIntentWording.js (shared)
 * -------------------------------------------
 * "IMPROVE WORDING WITH ADI" for the Project Report's Design Intent.
 *
 * The Design Intent is written by the engineering writer and saved beside the
 * report it was written for. This is the separate editorial job: ADI reads that
 * accepted narrative and improves how it reads. The engineering writer is not
 * asked again, no evidence is re-derived, and no engineering value is touched.
 *
 * WHERE IT READS FROM — nothing is assembled here that already exists:
 *
 *   - the saved narrative, from the report snapshot the report itself reads;
 *   - the frozen pack and the SCOPED writer input, from buildReportDesignIntentAttempt
 *     in prepare-only mode, which is the same evidence read and the same contract
 *     the narrative was written under.
 *
 * TWO MODES, one authority: the whole narrative, or the text the designer
 * highlighted. A highlighted rewrite is proposed WITHOUT a write and the editor
 * puts it back itself; the same action is then called again with the spliced copy,
 * which is checked mechanically to prove that nothing outside the selection
 * changed, and only then saved.
 *
 * WHAT IT MAY CHANGE: the words. The improved record carries the SAME evidence
 * identity, geometry and image fingerprints as the narrative it replaces, so a
 * narrative that was current stays current and one that had gone stale stays
 * stale. Nothing is regenerated by opening a report.
 *
 * UNDO IS DURABLE AND EXACT. The record that was replaced is kept whole — its own
 * text, its own timestamps and its own fingerprints — so undoing puts back exactly
 * what was there rather than a re-derivation of it.
 *
 * Pure apart from the injected calls: no React, no SDK, no runtime-specific APIs.
 */

import { buildReportDesignIntentAttempt } from './buildReportDesignIntentAttempt.js';
import {
  DESIGN_INTENT_STATUS,
  buildDesignIntentRecord,
} from './reportDesignIntentRecord.js';
import { DESIGN_INTENT_SECTION, designIntentSection } from './designIntentBrief.js';
import { publishedSectionFingerprint } from '../proposalApproval/sectionApprovalAuthority.js';
import { validateWriterOutput } from '../proposalWriter/writerOutputValidator.js';
import { buildAdiEditorialPrompt } from '../adiEditorial/adiEditorialPrompt.js';
import { ADI_WORDING_OUTCOME, runAdiWordingPass } from '../adiEditorial/adiWordingPass.js';
import { checkSelectionSpliceConservation, checkWordingConservation } from '../adiEditorial/adiWordingConservation.js';
import { ADI_REJECTION_STAGE, buildAdiRejectionDiagnostics } from '../adiEditorial/adiRejectionDiagnostics.js';

/** The action the caller asks for. */
export const ADI_INTENT_ACTION = Object.freeze({
  IMPROVE: 'improve',
  UNDO: 'undo',
});

/** What the caller is improving. */
export const ADI_INTENT_MODE = Object.freeze({
  SECTION: 'section',
  SELECTION: 'selection',
});

/** Why the editorial pass could not even be set up. */
export const ADI_INTENT_BLOCK = Object.freeze({
  INVALID_REQUEST: 'invalid_request',
  ACTION_UNKNOWN: 'unknown_action',
  NO_NARRATIVE: 'design_intent_missing',
  NOTHING_TO_UNDO: 'nothing_to_undo',
  NOTHING_SELECTED: 'nothing_selected',
  SPLICE_NOT_CONSERVED: 'selection_not_conserved',
});

function blocked(code, status, error, reason = null, diagnostics = null) {
  return { ok: false, block: { code, status, error, reason, diagnostics } };
}

/** A name for the record of who improved the wording. */
function byWhom(user) {
  return user?.full_name || user?.email || null;
}

/** The narrative's own words, where there is one to improve. */
function acceptedText(saved) {
  if (!saved || typeof saved !== 'object') return null;
  if (saved.status !== DESIGN_INTENT_STATUS.ACCEPTED) return null;
  const text = typeof saved.text === 'string' ? saved.text.trim() : '';
  return text.length > 0 ? text : null;
}

/**
 * THE REVALIDATION: the writer's own output validator, run again on the improved
 * wording, against the same scoped input the narrative was written under.
 *
 * The claim IDs supplied are the pack's own allowed set, and that is deliberate.
 * This is an EDITORIAL pass: the grounding of the copy being rewritten is not
 * re-derived here, it is carried by the conservation gate, which refuses any
 * figure, level, scope, product, limitation or claim the original wording did not
 * already carry. What this validator adds is every rule the rewrite could break on
 * its own — a figure the pack does not state, a blocked area, a scope the evidence
 * does not support, a capability claim with nothing behind it, design-stage
 * commentary, the section's word limit and the prose rules.
 */
function designIntentWordingValidator({ input, validate }) {
  const claimIds = (Array.isArray(input?.allowed_claims) ? input.allowed_claims : [])
    .map((claim) => claim?.claim_id)
    .filter(Boolean);

  return (proposed) => {
    const result = validate({
      input,
      output: {
        contract_version: input?.contract_version ?? null,
        pack_fingerprint: input?.evidence_pack?.pack_fingerprint ?? null,
        sections: [{
          section: DESIGN_INTENT_SECTION,
          text: proposed,
          claim_ids: claimIds,
        }],
      },
    });
    return { ok: result?.valid === true, violations: result?.violations || [] };
  };
}

/** The SAME evidence identity the narrative carries, never a new one. */
function carriedIdentity(saved) {
  return {
    sourceFingerprints: saved?.evidence_fingerprints || null,
    evidencePackFingerprint: saved?.evidence_pack_fingerprint ?? null,
    inputFingerprint: saved?.input_fingerprint ?? null,
    geometryFingerprint: saved?.geometry_fingerprint ?? null,
    visualFingerprint: saved?.visual_fingerprint ?? null,
    visualContext: saved?.visual_context ?? null,
  };
}

/** One uniform result, whatever the pass ended in. */
function result({ applied, action, outcome = null, mode, saved = null, improvedText = null, previousText = null, reason = null, diagnostics = null }) {
  return {
    ok: true,
    applied: Boolean(applied),
    action,
    outcome,
    mode,
    kept_original: outcome !== null && outcome !== ADI_WORDING_OUTCOME.IMPROVED,
    improved_text: improvedText,
    previous_text: previousText ?? (applied ? saved?.text : null) ?? null,
    text: applied ? (improvedText ?? saved?.text ?? null) : null,
    // Undo is offered only while the copy on screen is an ADI improvement whose
    // replaced wording is still held behind it.
    can_undo: action === ADI_INTENT_ACTION.UNDO ? false : Boolean(enabledUndo(saved)),
    reason,
    // The refusal read back in full, for the response alone. It is never written to
    // the snapshot — a refusal is a zero-write outcome.
    diagnostics,
  };
}

/** Whether this saved narrative has an earlier wording held behind it to restore. */
function enabledUndo(saved) {
  return saved?.editorial?.improved_at ? true : false;
}

/**
 * One editorial action on a saved Design Intent.
 *
 * @param {Object} input
 * @param {Object} input.entities — the user-scoped entity client (reads, and the save)
 * @param {Object} [input.authorityEntities] — the engineering-authority entity client
 * @param {Function} input.invokeLLM — the server-side provider call
 * @param {string} input.projectId
 * @param {string} input.versionId
 * @param {string} [input.action] — improve (default) or undo
 * @param {string} [input.mode] — section (default) or selection
 * @param {string} [input.selectionText] — exactly what the designer highlighted
 * @param {string} [input.improvedSelection] — what ADI returned for it, on the half
 *   of a selection edit that saves
 * @param {string} [input.bodyText] — the narrative after the editor spliced the
 *   improved selection in. Present only on the saving half of a selection edit.
 * @param {Object} [input.user]
 * @param {string} [input.now]
 * @param {string} [input.accountIdFallback]
 * @param {boolean} [input.isMasterAdmin]
 * @param {Function} [input.validate] — injected for tests; the writer's validator otherwise
 * @param {Function} [input.buildAttempt] — injected for tests; the one attempt builder otherwise
 * @returns {Promise<Object>} the outcome, or `{ ok: false, block }`
 */
export async function improveReportDesignIntentWording({
  entities,
  authorityEntities = null,
  invokeLLM,
  projectId = null,
  versionId = null,
  action = ADI_INTENT_ACTION.IMPROVE,
  mode = ADI_INTENT_MODE.SECTION,
  selectionText = '',
  improvedSelection = null,
  bodyText = null,
  user = null,
  now = null,
  accountIdFallback = null,
  isMasterAdmin = false,
  validate = null,
  buildAttempt = buildReportDesignIntentAttempt,
} = {}) {
  if (!projectId || !versionId) {
    return blocked(ADI_INTENT_BLOCK.INVALID_REQUEST, 400, 'project_id and version_id are required.');
  }
  if (action !== ADI_INTENT_ACTION.IMPROVE && action !== ADI_INTENT_ACTION.UNDO) {
    return blocked(ADI_INTENT_BLOCK.ACTION_UNKNOWN, 400, 'That editorial action is not available.');
  }

  // ── THE ONE EVIDENCE PATH, read in prepare-only mode ──
  // The project, the version, the switch, the frozen report evidence and the scoped
  // writer input, exactly as the writer's own attempt reads them — and no provider
  // call and no write.
  const prepared = await buildAttempt({
    entities,
    authorityEntities,
    invokeLLM,
    projectId,
    versionId,
    user,
    accountIdFallback,
    isMasterAdmin,
    now,
    prepareOnly: true,
  });
  if (!prepared?.ok) return { ok: false, block: prepared?.block };

  const { snapshot, flag, project, version, writerInput } = prepared;
  const payload = snapshot.payload && typeof snapshot.payload === 'object' ? snapshot.payload : {};
  const saved = payload.design_intent || null;
  const replaced = payload.design_intent_previous || null;
  const writerValidator = typeof validate === 'function' ? validate : validateWriterOutput;
  const revalidate = designIntentWordingValidator({ input: writerInput, validate: writerValidator });

  const saveImproved = async ({ text, previousText }) => {
    const improved = buildDesignIntentRecord({
      status: DESIGN_INTENT_STATUS.ACCEPTED,
      text,
      ...carriedIdentity(saved),
      providerIdentity: {
        provider: saved?.provider ?? null,
        model: saved?.model ?? null,
        promptVersion: saved?.prompt_version ?? null,
        contractVersion: saved?.contract_version ?? null,
        validatorFingerprint: saved?.validator_fingerprint ?? null,
        durationMs: saved?.duration_ms ?? null,
      },
      // The narrative's own generation identity is kept, and the editorial act is
      // recorded beside it: the words were written when they were written and
      // improved when they were improved.
      generatedAt: saved?.generated_at ?? null,
      generatedBy: saved?.generated_by ?? null,
      editorial: {
        improvedAt: now,
        improvedBy: byWhom(user),
        mode,
        // The wording revision that was replaced, and the one saved in its place:
        // the same identity the approval of a section copy is read from.
        sourceRevision: publishedSectionFingerprint(previousText),
        improvedRevision: publishedSectionFingerprint(text),
      },
    });

    await entities.ReportSnapshot.update(snapshot.id, {
      payload: { ...payload, design_intent: improved, design_intent_previous: saved },
    });
    return improved;
  };

  // ── UNDO: the copy that was replaced, put back exactly as it was ──
  if (action === ADI_INTENT_ACTION.UNDO) {
    if (!replaced || !enabledUndo(saved)) {
      return blocked(
        ADI_INTENT_BLOCK.NOTHING_TO_UNDO,
        409,
        'There is no earlier wording to restore for this report.',
      );
    }
    // The replaced copy is removed by rebuilding the payload without that key, so
    // the stored payload is exactly what the in-place removal produced.
    const { design_intent_previous: _removed, ...next } = payload;
    await entities.ReportSnapshot.update(snapshot.id, {
      payload: { ...next, design_intent: replaced },
    });
    return result({
      applied: true,
      action,
      mode,
      saved: replaced,
      outcome: ADI_WORDING_OUTCOME.UNCHANGED,
    });
  }

  const original = acceptedText(saved);
  if (!original) {
    return blocked(
      ADI_INTENT_BLOCK.NO_NARRATIVE,
      409,
      'This report has no accepted Design Intent to improve yet.',
    );
  }

  const section = designIntentSection(writerInput?.section_requirements) || {};
  const selection = String(selectionText || '');
  const saving = mode === ADI_INTENT_MODE.SELECTION && typeof bodyText === 'string';

  // ── A SELECTION EDIT SAVES ONLY WHAT IT CAN PROVE ──
  // The improved highlighted text is put back by the editor, and the copy it
  // splices into is read back here: the stored narrative with exactly that one
  // replacement has to read as the copy on screen. Anything else is refused before
  // it comes near the record, and the stored narrative is left untouched.
  if (saving) {
    if (!selection.trim() || String(improvedSelection || '').trim().length === 0) {
      return blocked(ADI_INTENT_BLOCK.NOTHING_SELECTED, 400, 'The highlighted text was not supplied.');
    }
    const conserved = checkSelectionSpliceConservation({
      originalBody: original,
      improvedBody: bodyText,
      selectionText: selection,
      improvedSelection,
    });
    if (!conserved.ok) {
      return blocked(
        ADI_INTENT_BLOCK.SPLICE_NOT_CONSERVED,
        409,
        'The copy outside the highlighted text changed, so nothing was saved.',
        conserved.violations?.[0]?.detail || null,
        buildAdiRejectionDiagnostics({
          originalText: original,
          proposedText: bodyText,
          stage: ADI_REJECTION_STAGE.SELECTION_CONSERVATION,
          violations: conserved.violations,
        }),
      );
    }
    // The replacement itself is held to the same two gates as a whole-section
    // rewrite: the meaning it may carry, and the writer's own rules.
    const whole = checkWordingConservation({ original, improved: bodyText });
    const checked = revalidate(improvedSelection);
    // The same two gates, each stating its own refusal, in the same order as
    // before: the meaning gate first, then the writer's own rules.
    if (!whole.ok) {
      return result({
        applied: false,
        action,
        mode,
        outcome: ADI_WORDING_OUTCOME.REJECTED,
        saved,
        reason: whole.violations?.[0]?.code || null,
        diagnostics: buildAdiRejectionDiagnostics({
          originalText: original,
          proposedText: bodyText,
          stage: ADI_REJECTION_STAGE.MEANING_CONSERVATION,
          violations: whole.violations,
        }),
      });
    }
    if (checked.ok !== true) {
      return result({
        applied: false,
        action,
        mode,
        outcome: ADI_WORDING_OUTCOME.REJECTED,
        saved,
        reason: checked.violations?.[0]?.code || null,
        diagnostics: buildAdiRejectionDiagnostics({
          originalText: selection,
          proposedText: improvedSelection,
          stage: ADI_REJECTION_STAGE.ORIGINAL_SURFACE_VALIDATOR,
          violations: checked.violations,
        }),
      });
    }
    const written = await saveImproved({ text: bodyText, previousText: original });
    return result({
      applied: true,
      action,
      mode,
      outcome: ADI_WORDING_OUTCOME.IMPROVED,
      saved: written,
      improvedText: bodyText,
      previousText: original,
    });
  }

  if (mode === ADI_INTENT_MODE.SELECTION && selection.trim().length === 0) {
    return blocked(ADI_INTENT_BLOCK.NOTHING_SELECTED, 400, 'Highlight the text to improve first.');
  }

  const prompt = buildAdiEditorialPrompt({
    sectionLabel: mode === ADI_INTENT_MODE.SELECTION
      ? section.title || 'the highlighted text'
      : section.title || 'Design Intent',
    mode,
    currentText: original,
    selectionText: selection,
    evidenceIdentity: {
      source: 'the published report evidence',
      evidence_pack_fingerprint: saved?.evidence_pack_fingerprint ?? null,
      report_or_report_type: 'Project Report',
    },
    documentIdentity: {
      project: project?.name || null,
      client: project?.client_name || null,
      version: version?.version_name || null,
    },
  });

  const pass = await runAdiWordingPass({
    flag,
    invokeLLM,
    prompt,
    original: mode === ADI_INTENT_MODE.SELECTION ? selection : original,
    mode,
    validate: revalidate,
    // The writer's own validator is what refuses the copy here, and the refusal is
    // read as that stage. Naming the stage decides nothing.
    validateStage: ADI_REJECTION_STAGE.ORIGINAL_SURFACE_VALIDATOR,
  });

  if (pass.outcome !== ADI_WORDING_OUTCOME.IMPROVED) {
    return result({
      applied: false,
      action,
      mode,
      outcome: pass.outcome,
      saved,
      previousText: mode === ADI_INTENT_MODE.SECTION ? original : null,
      reason: pass.violations?.[0]?.code || null,
      // Which stage refused it, the copy that was refused and every violation: the
      // refusal's own record, carried in the response and written nowhere.
      diagnostics: pass.diagnostics || null,
    });
  }

  // ── A HIGHLIGHTED REWRITE IS NOT SAVED UNTIL THE EDITOR HAS PUT IT BACK ──
  // The improved highlighted text goes back to the editor, which splices it into
  // the narrative and calls again with the spliced copy. Nothing is written here.
  if (mode === ADI_INTENT_MODE.SELECTION) {
    return result({
      applied: false,
      action: 'propose',
      mode,
      outcome: pass.outcome,
      saved,
      improvedText: pass.text,
    });
  }

  // ── THE ONE WRITE ──
  const written = await saveImproved({ text: pass.text, previousText: original });
  return result({
    applied: true,
    action,
    mode,
    outcome: ADI_WORDING_OUTCOME.IMPROVED,
    saved: written,
    improvedText: pass.text,
    previousText: original,
  });
}

export default improveReportDesignIntentWording;