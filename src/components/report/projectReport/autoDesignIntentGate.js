/**
 * autoDesignIntentGate.js
 * -----------------------
 * Pure decision: whether the auto-check effect in useAutoDesignIntent should
 * call `run` for the current snapshot. Extracted so the gate can be tested
 * without React.
 *
 * Ordinary viewing of a saved report (enabled === false) never triggers
 * generation. Explicit Update Report or first generation (enabled === true)
 * generates when the narrative is not current and a snapshot exists.
 *
 * Pure: no React, no fetching, no side effects.
 */

export function shouldAutoGenerateDesignIntent({ enabled, narrativeCurrent, snapshotExists }) {
  if (!enabled) return false;
  if (!snapshotExists) return false;
  return !narrativeCurrent;
}

export default shouldAutoGenerateDesignIntent;