// auto-design-intent-gate.test.mjs
// ---------------------------------------------------------------------------
// Tests for the Design Intent generation gate.
//
//   8. Opening an existing saved report (enabled=false) performs no generation.
//   9. An explicitly authorised Update Report (enabled=true) retains normal
//      generation behaviour.

import test from "node:test";
import assert from "node:assert/strict";
import { shouldAutoGenerateDesignIntent } from "../components/report/projectReport/autoDesignIntentGate.js";

test('8. Ordinary viewing (enabled=false) never generates', () => {
  assert.equal(
    shouldAutoGenerateDesignIntent({ enabled: false, narrativeCurrent: false, snapshotExists: true }),
    false,
  );
});

test('8b. Ordinary viewing with no current narrative still does not generate', () => {
  assert.equal(
    shouldAutoGenerateDesignIntent({ enabled: false, narrativeCurrent: false, snapshotExists: true }),
    false,
  );
});

test('9. Explicit update (enabled=true) generates when narrative is not current', () => {
  assert.equal(
    shouldAutoGenerateDesignIntent({ enabled: true, narrativeCurrent: false, snapshotExists: true }),
    true,
  );
});

test('9b. Explicit update does not generate when narrative is already current', () => {
  assert.equal(
    shouldAutoGenerateDesignIntent({ enabled: true, narrativeCurrent: true, snapshotExists: true }),
    false,
  );
});

test('9c. First generation (enabled=true, no snapshot yet) does not generate', () => {
  assert.equal(
    shouldAutoGenerateDesignIntent({ enabled: true, narrativeCurrent: false, snapshotExists: false }),
    false,
  );
});